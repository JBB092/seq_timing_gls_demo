"""Writes build/timing_cfg.svh for the approach A cells from the STA export.

Usage (from the repo root, after sta_export):
    python scripts/gen_timing_cfg.py [--csv build/sta/board_summary.csv]
                                     [--out build/timing_cfg.svh] [--period 10]

Each delay is a min:typ:max triplet:
    min = Fast 1100mV 0C
    typ = midpoint of min and max (an estimate, Quartus has no typical corner)
    max = Slow 1100mV 85C

The Cyclone V model reports uTco, uTsu and uTh as 0, so they are derived:
    T_STAGE = chain delay (LUT + wire) / number of stages, over all builds
    T_CO    = reg_in (last cell before the capture register)
    T_SU    = uncertainty - clock skew
    T_H     = 0
T_CO + T_SU is the same margin the STA uses, so the threshold matches it.
"""

import argparse
import csv
import statistics
import sys
from pathlib import Path

MIN_CORNER = "Fast 1100mV 0C"
MAX_CORNER = "Slow 1100mV 85C"


def corner_values(rows):
    stages = sum(int(r["stages"]) for r in rows)
    chain = sum(float(r["chain_cell"]) + float(r["chain_ic"]) for r in rows)
    # Median, so one odd placement does not move the value
    reg_in = statistics.median(float(r["reg_in"]) for r in rows)
    skew = statistics.median(float(r["clock_skew"]) for r in rows)
    unc = abs(statistics.median(float(r["uncertainty"]) for r in rows))
    return {
        "T_STAGE": chain / stages,
        "T_CO": reg_in,
        "T_SU": unc - skew,
        "T_H": 0.0,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--csv", default="build/sta/board_summary.csv")
    parser.add_argument("--out", default="build/timing_cfg.svh")
    parser.add_argument("--period", type=float, default=10.0,
                        help="clock period in ns, only for the printed threshold")
    args = parser.parse_args()

    csv_path = Path(args.csv)
    if not csv_path.exists():
        sys.exit(f"{csv_path} not found. Run the sta_export target first.")
    with csv_path.open(newline="") as f:
        rows = list(csv.DictReader(f))

    corners = {}
    for name in (MIN_CORNER, MAX_CORNER):
        selected = [r for r in rows if r["corner"] == name]
        if not selected:
            sys.exit(f"No rows for corner '{name}' in {csv_path}")
        corners[name] = corner_values(selected)
    depths = sorted({int(r["depth"]) for r in rows})

    lo, hi = corners[MIN_CORNER], corners[MAX_CORNER]
    triplets = {}
    for key in lo:
        mid = (lo[key] + hi[key]) / 2
        triplets[key] = (lo[key], mid, hi[key])

    lines = [
        "// Generated by scripts/gen_timing_cfg.py, do not edit.",
        f"// Source: {csv_path.as_posix()} (depths {' '.join(map(str, depths))})",
        f"// min = {MIN_CORNER}, typ = midpoint, max = {MAX_CORNER}",
        "// Values in ns (the cells use `timescale 1ns/1ps).",
        "`ifndef TIMING_CFG_SVH",
        "`define TIMING_CFG_SVH",
    ]
    for key, (a, b, c) in triplets.items():
        lines.append(f"`define {key:<8} {a:.3f}:{b:.3f}:{c:.3f}")
    lines.append("`endif")

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(("\n".join(lines) + "\n").encode())

    print(f"Written {out.as_posix()}")
    print(f"{'':10}{'min':>8}{'typ':>8}{'max':>8}")
    for key, values in triplets.items():
        print(f"{key:10}" + "".join(f"{v:8.3f}" for v in values))
    # Largest k with tCO + k*tStage + tSU <= T
    print(f"Largest passing depth at T = {args.period} ns:")
    for i, label in enumerate(("min", "typ", "max")):
        t = {k: v[i] for k, v in triplets.items()}
        k_max = int((args.period - t["T_CO"] - t["T_SU"]) // t["T_STAGE"])
        print(f"  {label}: k = {k_max}")


if __name__ == "__main__":
    main()
